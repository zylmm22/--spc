export function getSPCConstants(n: number): SPCConstants {
  const roundedN = Math.max(2, Math.min(25, Math.round(n)));
  if (SPC_FACTORS_TABLE[roundedN]) {
    return SPC_FACTORS_TABLE[roundedN];
  }
  
  // 插值或大样本近似计算
  const c4 = Math.sqrt(2 / (roundedN - 1)) * (1 - 1 / (4 * (roundedN - 1)));
  const d2 = Math.sqrt(2 * Math.log(roundedN)); // 近似
  return {
    n: roundedN,
    A2: 3 / (d2 * Math.sqrt(roundedN)),
    A3: 3 / (c4 * Math.sqrt(roundedN)),
    d2,
    d3: 0.7,
    D3: Math.max(0, 1 - 3 * 0.7 / d2),
    D4: 1 + 3 * 0.7 / d2,
    c4,
    B3: Math.max(0, 1 - 3 * Math.sqrt(1 - c4 * c4) / c4),
    B4: 1 + 3 * Math.sqrt(1 - c4 * c4) / c4
  };
}

